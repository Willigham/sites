/*eventos em javascript

1 onclick - quando o usuário clica no elemento
2 onmouseover - quando o usuário passa o mouse sobre o elemento
3 onmouseout - quando o usuário tira o mouse do elemento
4 onmousemove - quando o usuário move o mouse sobre o elemento
5 onmousedown - quando o usuário pressiona o botão do mouse sobre o elemento
6 onmouseup - quando o usuário solta o botão do mouse sobre o elemento
7 onfocus - quando o elemento recebe o foco
8 onblur - quando o elemento perde o foco
9 onchange - quando o valor do elemento muda
10 onkeydown - quando o usuário pressiona uma tecla
11 onkeypress - quando o usuário pressiona uma tecla (não é suportado em todos os navegadores)
12 onkeyup - quando o usuário solta uma tecla
13 onload - quando a página é carregada
14 onresize - quando a janela do navegador é redimensionada
15 onunload - quando a página é descarregada
*/ 