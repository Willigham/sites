// criando uma função switch
function verificarDia(cor) {
    switch (cor) {
        case "vermelho":
            console.log("A cor é vermelho");
            break;
        case "azul":
            console.log("A cor é azul");
            break;
        case "verde":
            console.log("A cor é verde");
            break;
        default:
            console.log("A cor não é vermelho, azul ou verde");
    }
}
